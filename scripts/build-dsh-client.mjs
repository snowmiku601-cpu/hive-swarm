import {readFile,writeFile,mkdtemp,rm} from 'node:fs/promises';
import {openSync,closeSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import {createRequire} from 'node:module';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {resolve,join,dirname,basename} from 'node:path';
import {tmpdir} from 'node:os';

const root=new URL('../',import.meta.url);
const packageRoot=new URL('packages/dsh-hive-swarm/',root);
function tooling(directory) {
  const bases=[new URL('package.json',root),new URL('package.json',packageRoot),new URL('.tmp/dsh-ui-build/package.json',root)];
  if(directory)bases.unshift(pathToFileURL(resolve(directory,'package.json')));
  for(const base of bases) {
    try{const require=createRequire(base);return {esbuild:require('esbuild'),require};}catch(error){if(error.code!=='MODULE_NOT_FOUND')throw error;}
  }
  throw Error('Run npm ci at the repository root to install the pinned esbuild development dependency.');
}

async function cliBuild(require) {
  // Restricted Windows hosts may deny a service pipe while permitting file-backed compiler output.
  const stage=await mkdtemp(join(tmpdir(),'hive-dsh-client-'));
  const graph=join(stage,'graph.cjs'),bees=join(stage,'bees.cjs'),icon=join(stage,'icon.mjs');
  try {
    for(const [kind,file,exportName] of [['graph',graph,'HiveGraph'],['bees',bees,'HiveBee']]) {
      const source=await readFile(new URL('hive-'+kind+'.js',root),'utf8');
      await writeFile(file,'var globalThis={};\n'+source+'\nmodule.exports=globalThis.'+exportName+';');
    }
    await writeFile(icon,'export default '+JSON.stringify((await readFile(new URL('assets/hive-swarm-icon.svg',root),'utf8')).replaceAll('\r\n','\n'))+';');
    const binary=require.resolve('@esbuild/'+process.platform+'-'+process.arch+'/'+(process.platform==='win32'?'esbuild.exe':'bin/esbuild'));
    const output=join(stage,'client.cjs'),meta=join(stage,'meta.json'),log=join(stage,'compiler.log');
    const fd=openSync(log,'wx');let result;
    try{result=spawnSync(binary,[fileURLToPath(new URL('client/index.jsx',packageRoot)),
      '--bundle','--format=cjs','--platform=browser','--target=chrome120','--jsx=transform','--minify','--legal-comments=none',
      '--external:react','--external:react/*','--external:@deepseek-ai/*','--loader:.css=text',
      '--alias:hive:graph='+graph,'--alias:hive:bees='+bees,'--alias:hive:icon='+icon,'--outfile='+output,'--metafile='+meta],
      {stdio:['ignore',fd,fd],windowsHide:true,timeout:60000});}
    finally{closeSync(fd);}
    if(result.error)throw result.error;
    if(result.status!==0)throw Error('esbuild failed: '+await readFile(log,'utf8'));
    return {outputFiles:[{text:await readFile(output,'utf8')}],metafile:JSON.parse(await readFile(meta,'utf8'))};
  } finally {
    if(resolve(dirname(stage))!==resolve(tmpdir())||!basename(stage).startsWith('hive-dsh-client-'))throw Error('Build staging boundary changed.');
    await rm(stage,{recursive:true,force:true});
  }
}

/** Bundle the existing UMD helpers in an isolated CJS namespace, without changing root assets. */
export async function buildClient({write=true,toolingDirectory}={}) {
  const {esbuild,require}=tooling(toolingDirectory);let compiler='api';let result;
  try{result=await esbuild.build({entryPoints:[fileURLToPath(new URL('client/index.jsx',packageRoot))],
    bundle:true,write:false,minify:true,format:'cjs',platform:'browser',target:['chrome120'],jsx:'transform',
    external:['react','react/*','@deepseek-ai/*'],loader:{'.css':'text'},legalComments:'none',metafile:true,
    plugins:[{name:'hive-canonical-assets',setup(build){
      build.onResolve({filter:/^hive:(graph|bees|icon)$/},args=>({path:args.path.slice(5),namespace:'hive'}));
      build.onLoad({filter:/\.css$/},async args=>({contents:(await readFile(args.path,'utf8')).replaceAll('\r\n','\n'),loader:'text'}));
      build.onLoad({filter:/.*/,namespace:'hive'},async args=>{
        if(args.path==='icon')return {contents:(await readFile(new URL('assets/hive-swarm-icon.svg',root),'utf8')).replaceAll('\r\n','\n'),loader:'text'};
        const source=await readFile(new URL('hive-'+args.path+'.js',root),'utf8');
        return {contents:'var globalThis = {};\n'+source+'\nmodule.exports = globalThis.'+(args.path==='graph'?'HiveGraph':'HiveBee')+';',loader:'js'};
      });
    }}]});}catch(error){if(error.code!=='EPERM')throw error;compiler='cli';result=await cliBuild(require);}
  const code='// Generated by scripts/build-dsh-client.mjs. Host React is intentionally external.\n'+
    'window.__ModuleLoader__.load({id:"dsh-hive-swarm",factory(require){\nvar module={exports:{}};var exports=module.exports;\n'+
    result.outputFiles[0].text+'\nreturn module.exports;\n}});\n';
  const output=fileURLToPath(new URL('client/dist.js',packageRoot));
  if(write)await writeFile(output,code);
  return {code,output,bytes:Buffer.byteLength(code),metafile:result.metafile,version:esbuild.version,compiler};
}
if(process.argv[1]&&pathToFileURL(resolve(process.argv[1])).href===import.meta.url) {
  const result=await buildClient();console.log(JSON.stringify({output:result.output,bytes:result.bytes,esbuild:result.version,compiler:result.compiler}));
}
